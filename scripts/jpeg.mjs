function huffTable([counts, vals]) {
  const t = {}; let code = 0, k = 0;
  for (let len = 1; len <= 16; len++) { for (let i = 0; i < counts[len - 1]; i++) t[vals[k++]] = [code++, len]; code <<= 1; }
  return t;
}
function scaleQ(base, quality) {
  const s = quality < 50 ? 5000 / quality : 200 - quality * 2;
  return base.map((q) => Math.min(255, Math.max(1, Math.floor((q * s + 50) / 100))));
}
const C = Array.from({ length: 8 }, (_, u) => Array.from({ length: 8 }, (_, x) => Math.cos(((2 * x + 1) * u * Math.PI) / 16) * (u ? Math.sqrt(2 / 8) : Math.sqrt(1 / 8))));
function fdct(b) {
  const tmp = new Float64Array(64), out = new Float64Array(64);
  for (let y = 0; y < 8; y++) for (let u = 0; u < 8; u++) { let s = 0; for (let x = 0; x < 8; x++) s += C[u][x] * b[y * 8 + x]; tmp[y * 8 + u] = s; }
  for (let u = 0; u < 8; u++) for (let v = 0; v < 8; v++) { let s = 0; for (let y = 0; y < 8; y++) s += C[v][y] * tmp[y * 8 + u]; out[v * 8 + u] = s; }
  return out;
}

export function encodeJPEG(w, h, rgba, quality = 82) {
  const ql = scaleQ(QL, quality), qc = scaleQ(QC, quality);
  const hdl = huffTable(DC_L), hdc = huffTable(DC_C), hal = huffTable(AC_L), hac = huffTable(AC_C);
  const bytes = [];
  let bitBuf = 0, bitCnt = 0;
  const put = (code, len) => {
    bitBuf = (bitBuf << len) | code; bitCnt += len;
    while (bitCnt >= 8) { const b = (bitBuf >> (bitCnt - 8)) & 255; bytes.push(b); if (b === 255) bytes.push(0); bitCnt -= 8; }
    bitBuf &= (1 << bitCnt) - 1;
  };
  const cat = (v) => { const a = Math.abs(v); return a ? 32 - Math.clz32(a) : 0; };
  const bitsOf = (v, n) => (v < 0 ? v + (1 << n) - 1 : v);
  const block = (data, q, prevDC, hd, ha) => {
    const d = fdct(data);
    const z = new Int32Array(64);
    for (let i = 0; i < 64; i++) z[i] = Math.round(d[ZZ[i]] / q[ZZ[i]]);
    const diff = z[0] - prevDC, c0 = cat(diff);
    put(...hd[c0]); if (c0) put(bitsOf(diff, c0), c0);
    let run = 0;
    for (let i = 1; i < 64; i++) {
      if (z[i] === 0) { run++; continue; }
      while (run > 15) { put(...ha[0xf0]); run -= 16; }
      const c = cat(z[i]); put(...ha[(run << 4) | c]); put(bitsOf(z[i], c), c); run = 0;
    }
    if (run) put(...ha[0]);
    return z[0];
  };
  const head = [];
  const seg = (marker, data) => { head.push(0xff, marker, (data.length + 2) >> 8, (data.length + 2) & 255, ...data); };
  head.push(0xff, 0xd8);
  seg(0xe0, [0x4a, 0x46, 0x49, 0x46, 0, 1, 1, 0, 0, 1, 0, 1, 0, 0]);
  seg(0xdb, [0, ...ZZ.map((i) => ql[i]), 1, ...ZZ.map((i) => qc[i])]);
  seg(0xc0, [8, h >> 8, h & 255, w >> 8, w & 255, 3, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1]);
  for (const [cls, id, t] of [[0, 0, DC_L], [1, 0, AC_L], [0, 1, DC_C], [1, 1, AC_C]]) seg(0xc4, [(cls << 4) | id, ...t[0], ...t[1]]);
  seg(0xda, [3, 1, 0x00, 2, 0x11, 3, 0x11, 0, 63, 0]);
  const px = (x, y, c) => rgba[(Math.min(h - 1, y) * w + Math.min(w - 1, x)) * 4 + c];
  let pY = 0, pCb = 0, pCr = 0;
  const Y = new Float64Array(64), Cb = new Float64Array(64), Cr = new Float64Array(64);
  for (let my = 0; my < h; my += 16) for (let mx = 0; mx < w; mx += 16) {
    for (const [ox, oy] of [[0, 0], [8, 0], [0, 8], [8, 8]]) {
      for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) { const r = px(mx + ox + x, my + oy + y, 0), g = px(mx + ox + x, my + oy + y, 1), b = px(mx + ox + x, my + oy + y, 2); Y[y * 8 + x] = 0.299 * r + 0.587 * g + 0.114 * b - 128; }
      pY = block(Y, ql, pY, hdl, hal);
    }
    for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
      let r = 0, g = 0, b = 0;
      for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) { r += px(mx + 2 * x + dx, my + 2 * y + dy, 0); g += px(mx + 2 * x + dx, my + 2 * y + dy, 1); b += px(mx + 2 * x + dx, my + 2 * y + dy, 2); }
      r /= 4; g /= 4; b /= 4;
      Cb[y * 8 + x] = -0.168736 * r - 0.331264 * g + 0.5 * b; Cr[y * 8 + x] = 0.5 * r - 0.418688 * g - 0.081312 * b;
    }
    pCb = block(Cb, qc, pCb, hdc, hac); pCr = block(Cr, qc, pCr, hdc, hac);
  }
  if (bitCnt) put((1 << (8 - bitCnt)) - 1, 8 - bitCnt);
  return Buffer.from([...head, ...bytes, 0xff, 0xd9]);
}
